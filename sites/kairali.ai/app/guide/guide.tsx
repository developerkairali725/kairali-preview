// from docs/sops/*.md via marked — the md files are the source of truth) inside
// the Fleet Pulse look. Content files live in sites/kairali.ai/content/.
import { readFileSync } from "node:fs";
import { join } from "node:path";

const CSS = `
  .gwrap{max-width:920px;margin:0 auto;padding:36px 24px 100px;color:#1A2E1A;font:16px/1.66 ui-sans-serif,system-ui,sans-serif}
  .gwrap h1{font-size:30px;letter-spacing:-.5px;line-height:1.2;margin:16px 0 4px}
  .gwrap h1+h2{font-size:18px;color:#6B6350;font-weight:500;margin-top:0;border:none;padding-top:0}
  .gwrap h2{font-size:23px;letter-spacing:-.3px;margin:48px 0 8px;padding-top:14px;border-top:1px solid #E6E0CF}
  .gwrap h3{font-size:18px;margin:26px 0 8px;color:#003720}
  .gwrap p{margin:11px 0} .gwrap ul,.gwrap ol{margin:11px 0;padding-left:24px} .gwrap li{margin:6px 0}
  .gwrap a{color:#003720} .gwrap strong{color:#101F10}
  .gwrap code{background:#EFE9DC;padding:1px 6px;border-radius:5px;font-size:.88em;font-family:ui-monospace,Menlo,monospace}
  .gwrap pre{background:#1f2724;color:#e9ede9;border-radius:12px;padding:16px 18px;overflow-x:auto;font-size:13.5px;line-height:1.6;margin:16px 0}
  .gwrap pre code{background:none;padding:0;color:inherit}
  .gwrap blockquote{margin:16px 0;padding:13px 16px 13px 18px;border-radius:12px;background:#fff;border:1px solid #E6E0CF;border-left:5px solid #6B6350;font-size:15px}
  .gwrap blockquote p{margin:6px 0}
  .gwrap table{border-collapse:collapse;width:100%;margin:16px 0;font-size:14.5px;background:#fff;border-radius:10px;overflow:hidden;display:block;overflow-x:auto}
  .gwrap th,.gwrap td{border:1px solid #E6E0CF;padding:9px 12px;text-align:left;vertical-align:top}
  .gwrap th{background:#DBE2C1;color:#38471A;font-weight:700}
  .gwrap hr{border:none;border-top:1px solid #E6E0CF;margin:40px 0}
`;

export function GuidePage({ file, title }: { file: string; title: string }) {
  // Safety note (re dangerouslySetInnerHTML): `file` is a hardcoded constant per
  // route (never user input), and the HTML is OUR OWN build-time artifact —
  // generated by `marked` from repo-committed docs/sops/*.md and reviewed like
  // any other code in the PR. No untrusted content ever flows through here.
  const html = readFileSync(join(process.cwd(), "content", file), "utf8");
  return (
    <main style={{ background: "#FFFDF7", minHeight: "100vh" }}>
      <style>{CSS}</style>
      <div className="gwrap">
        <p style={{ letterSpacing: ".16em", textTransform: "uppercase", fontSize: 12, fontWeight: 700, color: "#6B6350", margin: 0 }}>
          Kairali Playbook · {title}
        </p>
        <div dangerouslySetInnerHTML={{ __html: html }} />
      </div>
    </main>
  );
}
