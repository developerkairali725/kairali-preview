import { routeRobots } from "./robots-policy";
/**
 * AHV English candidate — per-route head metadata.
 *
 * Every fact here is READ from the approved package: the route's own dataset
 * record where it has one, otherwise its view's helmet. Nothing is composed,
 * improved or invented (HARD GATE 6) — including the source's own duplicate
 * and mismatched titles, which are preserved and reported, not fixed.
 *
 * Robots are emitted server-side from the production policy; boot.ts enforces
 * the same value after imported designs write their head. Staging retains its
 * response-header and robots.txt locks. Canonicals retain their route-specific
 * server emission and runtime deduplication.
 */
import type { Metadata } from "next";
import type { CandidateRoute } from "./registry";
import OG_IMAGES from "../../../english-candidate/og-images.json";
import CANONICAL_SERVER from "../../../english-candidate/canonical-server-routes.json";

/**
 * Exception to "canonical is the design's to write" (header note): a 254-route
 * sweep on 2026-09-23 found 13 families whose renderer writes NO canonical after
 * mounting (english-candidate/canonical-server-routes.json). For those routes,
 * and only those, the manifest's canonical is emitted here — it is the only tag
 * in the head, so the duplicate the note guards against cannot occur, and
 * boot.ts's governedWins() would drop a second one anyway.
 */
const CANONICAL_SERVER_ROUTES = new Set<string>(CANONICAL_SERVER.routes);

/**
 * Share-card images, generated by tools/build-og-images.mjs from the site's own
 * image bank into public/images/og/ -- 1200x630 baseline JPEG, each under the
 * ~300 KB that WhatsApp previews reliably render. This REPLACES the source's
 * og:image, and deliberately so: measured 2026-09-16, 71 routes declared no
 * image at all (their card rendered as a bare text link), 180 pointed at
 * /wp-content/ on the production domain (which the new host does not serve, so
 * they break the moment DNS moves), and the homepage's pointed at /og-card.jpg,
 * which already returns 404 on production today. Between them, every page.
 * The width/height/type/alt subproperties let Meta draw the card without first
 * downloading and measuring the image. secure_url and the absolute origin are
 * the locked public domain.
 */
const SITE_ORIGIN = "https://ayurvedichealingvillage.com";
const OG_MAP: Record<string, string> = OG_IMAGES as Record<string, string>;
function shareImage(route: CandidateRoute) {
  const path = OG_MAP[route.path];
  if (!path) return null;
  const url = SITE_ORIGIN + path;
  return { url, secureUrl: url, width: 1200, height: 630, type: "image/jpeg",
    alt: route.metadata.ogTitle ?? route.metadata.title ?? "Kairali – The Ayurvedic Healing Village" };
}

export function routeMetadata(route: CandidateRoute): Metadata {
  const m = route.metadata;
  const robots = routeRobots(route);
  const meta: Metadata = {
    robots: { index: !robots.includes("noindex"), follow: !robots.includes("nofollow") },
    title: m.title ?? "Kairali — The Ayurvedic Healing Village",
  };
  if (m.description) meta.description = m.description;
  if (m.canonical && CANONICAL_SERVER_ROUTES.has(route.path)) meta.alternates = { canonical: m.canonical };

  const ogTitle = m.ogTitle ?? m.title;
  const ogDescription = m.ogDescription ?? m.description;
  if (ogTitle || ogDescription || m.ogImage) {
    meta.openGraph = {
      ...(ogTitle ? { title: ogTitle } : {}),
      ...(ogDescription ? { description: ogDescription } : {}),
      ...((): object => { const img = shareImage(route); return img ? { images: [img] } : m.ogImage ? { images: [m.ogImage] } : {}; })(),
      ...(m.canonical ? { url: m.canonical } : {}),
      type: m.ogType === "article" ? "article" : "website",
      siteName: "Kairali – The Ayurvedic Healing Village",
      locale: "en_US",
    };
  }
  const share = shareImage(route);
  if (share) {
    meta.twitter = {
      card: "summary_large_image",
      title: ogTitle ?? undefined,
      description: ogDescription ?? undefined,
      images: [{ url: share.url, alt: share.alt, width: 1200, height: 630 }],
    };
  }
  return meta;
}
