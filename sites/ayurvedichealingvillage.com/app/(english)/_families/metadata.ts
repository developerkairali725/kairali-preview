import { routeRobots } from "./robots-policy";
/**
 * AHV English candidate — per-route head metadata.
 *
 * Every fact here is READ from the approved package: the route's own dataset
 * record where it has one, otherwise its view's helmet. Nothing is composed,
 * improved or invented (HARD GATE 6) — including the source's own duplicate
 * and mismatched titles, which are preserved and reported, not fixed.
 *
 * Robots are emitted server-side from the production policy; boot.ts enforces
 * the same value after imported designs write their head. Staging retains its
 * response-header and robots.txt locks. Canonicals retain their route-specific
 * server emission and runtime deduplication.
 */
import type { Metadata } from "next";
import type { CandidateRoute } from "./registry";
import OG_IMAGES from "../../../english-candidate/og-images.json";
import { LOCALE_INFO, TARGET_CODES, alternates, canonicalUrl, localeData, localizedPath, type LocaleCode } from "./l10n";
import { serverCanonical } from "./canonical-policy.mjs";

/**
 * Canonical in the raw HTML (SEO-D22 / D-10, 29 Sep 2026). Until then only the
 * 13 routes whose renderer writes NO canonical after mounting
 * (english-candidate/canonical-server-routes.json, sweep of 2026-09-23) and
 * alias routes emitted one server-side, so 238 English routes reached
 * non-JS crawlers without a canonical. Every route with a manifest canonical
 * now emits it: the value is the one its own view helmet / dataset record
 * writes after mounting (pinned equal by test/seo-d22.test.mjs), and boot.ts's
 * governedWins() keeps a single tag after hydration. See canonical-policy.mjs.
 */

/**
 * Share-card images, generated by tools/build-og-images.mjs from the site's own
 * image bank (or owner-selected homepage artwork) into public/images/og/ --
 * 1200x630 baseline JPEG, each within the internal 300 KB size budget.
 * This REPLACES the source's
 * og:image, and deliberately so: measured 2026-09-16, 71 routes declared no
 * image at all (their card rendered as a bare text link), 180 pointed at
 * /wp-content/ on the production domain (which the new host does not serve, so
 * they break the moment DNS moves), and the homepage's pointed at /og-card.jpg,
 * which already returns 404 on production today. Between them, every page.
 * The width/height/type/alt subproperties let Meta draw the card without first
 * downloading and measuring the image. secure_url and the absolute origin are
 * the locked public domain.
 */
const SITE_ORIGIN = "https://ayurvedichealingvillage.com";
const OG_MAP: Record<string, string> = OG_IMAGES as Record<string, string>;
function shareImage(route: CandidateRoute, altText?: string | null) {
  const path = OG_MAP[route.path];
  if (!path) return null;
  const url = SITE_ORIGIN + path;
  return { url, secureUrl: url, width: 1200, height: 630, type: "image/jpeg",
    alt: route.path === "/"
      ? "Woman receiving an Ayurvedic shoulder massage in a green, sunlit treatment setting"
      : altText ?? route.metadata.ogTitle ?? route.metadata.title ?? "Kairali – The Ayurvedic Healing Village" };
}

/**
 * Localized head (25 Sep 2026). Title/description/OG come from the SAME
 * accepted catalogue as the page body (l10n/generated/<locale>.json, built by
 * tools/l10n/build.mjs); a field without an accepted translation keeps the
 * English value. Canonical is the page's own localized URL (never the English
 * one); hreflang lists every real equivalent plus x-default = English. Both are
 * generated from the reviewed route table, not translated.
 */
function localizedFields(route: CandidateRoute, locale: LocaleCode) {
  const m = route.metadata;
  if (locale === "en") return m;
  const d = localeData(locale)?.meta[route.path];
  const canonical = canonicalUrl(route.path, locale);
  return {
    ...m,
    title: d?.title ?? m.title,
    description: d?.description ?? m.description,
    ogTitle: d?.ogTitle ?? d?.title ?? m.ogTitle,
    ogDescription: d?.ogDescription ?? d?.description ?? m.ogDescription,
    canonical,
  };
}

export function routeMetadata(route: CandidateRoute, locale: LocaleCode = "en"): Metadata {
  const m = localizedFields(route, locale);
  const robots = routeRobots(route);
  const meta: Metadata = {
    robots: { index: !robots.includes("noindex"), follow: !robots.includes("nofollow") },
    title: m.title ?? "Kairali — The Ayurvedic Healing Village",
  };
  if (m.description) meta.description = m.description;
  const langs = alternates(route.path);
  const hasCluster = Object.keys(langs).length > 2;
  if (locale !== "en") meta.alternates = { canonical: m.canonical, ...(hasCluster ? { languages: langs } : {}) };
  else {
    // Alias routes (canonical points at ANOTHER page, e.g. /panchakarma/ → /panchakarma-therapy/, owner 25 Sep) also
    // emit it server-side: a crawler reading the raw HTML must see the consolidation, not only the runtime pass
    // (staging SEO pass 28 Sep 2026). boot.ts's governedWins() keeps one canonical after hydration.
    // Since 29 Sep (D-10) the same holds for every self-canonical route too.
    const canonical = serverCanonical(route);
    if (canonical) meta.alternates = { canonical };
    if (hasCluster) meta.alternates = { ...(meta.alternates ?? {}), languages: langs };
  }

  const ogTitle = m.ogTitle ?? m.title;
  const ogDescription = m.ogDescription ?? m.description;
  if (ogTitle || ogDescription || m.ogImage) {
    meta.openGraph = {
      ...(ogTitle ? { title: ogTitle } : {}),
      ...(ogDescription ? { description: ogDescription } : {}),
      ...((): object => { const img = shareImage(route, m.ogTitle ?? m.title); return img ? { images: [img] } : m.ogImage ? { images: [m.ogImage] } : {}; })(),
      ...(m.canonical ? { url: m.canonical } : {}),
      type: m.ogType === "article" ? "article" : "website",
      siteName: "Kairali – The Ayurvedic Healing Village",
      locale: LOCALE_INFO[locale].og,
      alternateLocale: (["en", ...TARGET_CODES] as LocaleCode[]).filter((c) => c !== locale && localizedPath(route.path, c)).map((c) => LOCALE_INFO[c].og),
    };
  }
  const share = shareImage(route, m.ogTitle ?? m.title);
  if (share) {
    meta.twitter = {
      card: "summary_large_image",
      title: ogTitle ?? undefined,
      description: ogDescription ?? undefined,
      images: [{ url: share.url, alt: share.alt, width: 1200, height: 630 }],
    };
  }
  return meta;
}
