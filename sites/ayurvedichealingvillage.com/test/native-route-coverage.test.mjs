import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {join} from 'node:path';
const root=fileURLToPath(new URL('..',import.meta.url));
test('every registered native page is excluded from legacy static generation to prevent Vercel output collisions',()=>{
 const manifest=JSON.parse(readFileSync(join(root,'english-candidate/route-manifest.json'),'utf8'));
 const source=readFileSync(join(root,'app/(english)/[...slug]/page.tsx'),'utf8');
 const exclusions=new Set(JSON.parse(source.match(/const nativePages = new Set\((\[[^;]+\])\)/)[1]));
 const native=manifest.routes.filter(r=>r.segments.length&&['tsx','ts','jsx','js'].some(ext=>existsSync(join(root,'app/(english)',...r.segments,'page.'+ext))));
 assert.ok(native.length>=4);
 for(const route of native)assert.ok(exclusions.has(route.path),`${route.path} would also be generated by the legacy catch-all`);
});

// Finder programme URLs must retain the full package renderer. A static page
// in another route group wins over the English catch-all even if the URL is valid.
const finderIndex=JSON.parse(readFileSync(join(root,'public/ahv/search-index.json'),'utf8'));
for(const programme of finderIndex.programmes) test(`finder package keeps the English page lane: ${programme.route}`,()=>{
 const segments=programme.route.split('/').filter(Boolean);
 for(const group of ['(campaign)','(lp)']) for(const ext of ['tsx','ts','jsx','js'])
  assert.equal(existsSync(join(root,'app',group,...segments,'page.'+ext)),false,
   `${programme.route} is shadowed by a ${group} landing page; restore its package route`);
});
