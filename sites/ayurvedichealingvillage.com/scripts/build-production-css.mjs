import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";
const site=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
export const sources=["campaign-v110/integration.css","public/design/campaign-bundle.css","campaign-v2/styles/base.css","campaign-v2/sections/sections.css","campaign-v2/production/production.css"];
export function productionCss(){
 return "/* Generated by scripts/build-production-css.mjs. Preserve source order. */\n"+sources.map(name=>{
  let css=fs.readFileSync(path.join(site,name),"utf8");
  if(name==="campaign-v2/styles/base.css")css=css.replace('@import "@kairali/ui/ahv-campaign-tokens.css";',fs.readFileSync(path.resolve(site,"../../packages/ui/ahv-campaign-tokens.css"),"utf8"));
  if(/@import\s/.test(css))throw Error("Unresolved CSS import: "+name);
  return "/* Source: "+name+" */\n"+css;
 }).join("\n");
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))fs.writeFileSync(path.join(site,"campaign-v2/production/document.css"),productionCss());
