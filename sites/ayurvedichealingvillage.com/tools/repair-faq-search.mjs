#!/usr/bin/env node
/**
 * AHV /faqs-downloads/ — the FAQ filter on the shared search engine (D-20260922-26;
 * brainstorm §5.1). Applied to the SERVED views (public/ahv/views/…faqs-and-downloads…)
 * AND the design overlay (english-candidate/package-overlay/AHV Page FAQs and
 * Downloads {Desktop,Mobile}.dc.html) so the next import derives the same page.
 *
 * What changes — behaviour only, never the 44 questions or their answers:
 *   · every <details data-q> gets a stable id q-01 … q-44 in document order (the deep-link
 *     contract the header overlay uses: /faqs-downloads/?q=<text>#q-NN);
 *   · the filter input goes from 17px to 18px (45+ rule 1); the bar is otherwise the design's;
 *   · the empty state gains the fallback row: WhatsApp +91 92898 38797 · free online
 *     consultation · info@kairali.com (locked facts only);
 *   · the logic: predictive + typo-tolerant matching through window.AHVSearch (scope "faq";
 *     the hand-written keywords come from the built index, /ahv/search-index.json), ranked
 *     order inside each topic, matched words highlighted in the question line only, auto-open
 *     when ≤5 match, "Showing N questions for “visa” — you typed “vissa”", ?q= and #q-NN deep
 *     links. Until the engine has loaded (or if it never does) the filter falls back to
 *     word-boundary substring matching, so it never does less than the design did.
 *
 * Idempotent (ids and the 18px input are recognised; the logic is replaced wholesale, marked).
 *   node tools/repair-faq-search.mjs [--dry]
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SITE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DRY = process.argv.includes("--dry");
const MARK = "// ahv-faq-search v2026-09-23d";

const LOGIC = `${MARK} — generated by tools/repair-faq-search.mjs (D-20260922-26). Same engine as the header search and the finder.
class Component extends DCLogic {
  componentDidMount() {
    // The template never binds ref="{{ rootRef }}" (so the design's own filter never ran in a browser), and the
    // server response carries a prerendered SNAPSHOT of this same markup ([data-ahv-snapshot]) — the live view's
    // nodes are the ones OUTSIDE the snapshot. Retry briefly in case the view is not attached yet.
    let attempts = 0;
    const boot = () => { if (this._init()) return; if (++attempts < 40) this._retry = setTimeout(boot, 100); };
    boot();
  }
  _init() {
    const scope = this.root || document.getElementById('ahv-design-root') || document;
    const live = el => el && !el.closest('[data-ahv-snapshot]');
    const q1 = sel => Array.from(scope.querySelectorAll(sel)).filter(live)[0] || null;
    const qa = sel => Array.from(scope.querySelectorAll(sel)).filter(live);
    const input = q1('[data-filter]');
    const status = q1('[data-status]');
    const clear = q1('[data-clear]');
    const groups = qa('[data-group]');
    const rails = qa('[data-rail]');
    const empty = q1('[data-empty]');
    if (!input || !status || !groups.length) return false;
    const root = { querySelector: sel => q1(sel), querySelectorAll: sel => qa(sel) };
    const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
    const fold = s => String(s || '').toLowerCase().normalize('NFD').replace(/[\\u0300-\\u036f]/g, '').replace(/[’'\`´]/g, '');
    const items = [];
    groups.forEach(g => {
      g._ahvItems = Array.from(g.querySelectorAll('[data-q]'));
      g._ahvItems.forEach((d, i) => {
        if (!d.id) d.id = 'q-' + String(items.length + 1).padStart(2, '0');
        const h = d.querySelector('h3, h2, summary > span:last-child') || d.querySelector('summary');
        d._ahvH = h; d._ahvHtml = h ? h.innerHTML : ''; d._ahvText = h ? h.textContent.trim() : '';
        d._ahvAnswer = (d.textContent || '').replace(d._ahvText, '').replace(/\\s+/g, ' ').trim().slice(0, 1500);
        d._ahvTopic = g.getAttribute('data-label') || '';
        items.push(d);
      });
    });
    const total = items.length, topics = groups.length;
    const sync = d => { const m = d.querySelector('[data-mark]'); if (m) m.textContent = d.open ? '\\u2212' : '+'; };
    items.forEach(d => { sync(d); d.addEventListener('toggle', () => sync(d)); });
    const docs = items.map((d, i) => ({ id: d.id, n: i + 1, topic: d._ahvTopic, q: d._ahvText, a: d._ahvAnswer, kw: [] }));
    let engine = null;
    let deepLinkActive = true;
    const mark = (d, hits) => {
      if (!d._ahvH) return;
      if (!hits || !hits.length) { d._ahvH.innerHTML = d._ahvHtml; return; }
      const words = hits.filter(w => w.length >= 3).sort((a, b) => b.length - a.length).map(w => w.replace(/[.*+?^\${}()|[\\]\\\\]/g, '\\\\$&'));
      if (!words.length) { d._ahvH.innerHTML = d._ahvHtml; return; }
      d._ahvH.innerHTML = esc(d._ahvText).replace(new RegExp('(^|[^a-z0-9])(' + words.join('|') + ')', 'ig'), (m, pre, w) => pre + '<mark style="background:linear-gradient(transparent 62%,#F3DFA8 62%);color:inherit;padding:0 1px">' + w + '</mark>');
    };
    const apply = () => {
      const typed = input.value.trim();
      let ranked = null, corrected = null;
      if (typed.length >= 2) {
        ranked = new Map();
        if (engine) {
          const r = engine.query(typed, { scope: 'faq', limit: 60 });
          r.questions.forEach((x, i) => ranked.set(x.id, { i: i, hits: x.hits }));
          corrected = r.corrected;
          clearTimeout(this._track); this._track = setTimeout(() => { if (window.AHVSearch && window.AHVSearch.track) window.AHVSearch.track('faq', typed, r.questions.length); }, 900);
        } else {
          const words = fold(typed).split(/\\s+/).filter(Boolean);
          items.forEach(d => {
            const hay = fold(d.textContent);
            if (words.every(w => new RegExp('(^|[^a-z0-9])' + w.replace(/[.*+?^\${}()|[\\]\\\\]/g, '\\\\$&')).test(hay))) ranked.set(d.id, { i: ranked.size, hits: words });
          });
        }
      }
      const forced = deepLinkActive && location.hash && /^#q-\\d+$/.test(location.hash) ? location.hash.slice(1) : null;
      let hits = 0;
      const open = ranked && ranked.size <= 5;
      groups.forEach(g => {
        const its = g._ahvItems;
        const shown = ranked ? its.filter(d => ranked.has(d.id) || d.id === forced) : its.slice();
        if (ranked) shown.sort((a, b) => (ranked.has(a.id) ? ranked.get(a.id).i : 99) - (ranked.has(b.id) ? ranked.get(b.id).i : 99));
        // ranked order inside the topic; original order when the filter is empty
        (ranked ? shown.concat(its.filter(d => shown.indexOf(d) < 0)) : its).forEach(d => g.appendChild(d));
        its.forEach(d => {
          const on = shown.indexOf(d) >= 0;
          d.style.display = on ? '' : 'none';
          d.open = on && (d.id === forced || (ranked && open));
          mark(d, ranked && on && ranked.has(d.id) ? ranked.get(d.id).hits : null);
          sync(d);
        });
        g.style.display = shown.length ? '' : 'none';
        hits += shown.length;
      });
      rails.forEach(a => { const t = root.querySelector(a.getAttribute('href')); a.style.opacity = (t && t.style.display !== 'none') ? '1' : '0.35'; });
      if (empty) empty.style.display = hits ? 'none' : '';
      if (clear) clear.style.display = typed ? '' : 'none';
      const qn = (n) => n + (n === 1 ? ' question' : ' questions');
      status.textContent = !ranked
        ? 'Showing all ' + total + ' questions in ' + topics + ' topics'
        : hits === 0
          ? 'No question matches \\u201C' + typed + '\\u201D \\u2014 ask us directly:'
          : corrected
            ? 'Showing ' + qn(hits) + ' for \\u201C' + corrected + '\\u201D \\u2014 you typed \\u201C' + typed + '\\u201D'
            : qn(hits) + (hits === 1 ? ' matches ' : ' match ') + '\\u201C' + typed + '\\u201D';
    };
    input.addEventListener('input', () => { deepLinkActive = false; apply(); });
    if (clear) clear.addEventListener('click', () => { deepLinkActive = false; input.value = ''; apply(); input.focus(); });
    // deep links: ?q=<text> pre-fills the filter, #q-NN opens that question
    try {
      const u = new URLSearchParams(location.search);
      if (u.get('q')) input.value = u.get('q').slice(0, 120);
    } catch (e) { /* no URL API */ }
    apply();
    if (location.hash && /^#q-\\d+$/.test(location.hash)) {
      const d = root.querySelector(location.hash);
      if (d) { d.style.scrollMarginTop = '120px'; d.open = true; sync(d); setTimeout(() => { try { d.scrollIntoView({ block: 'start' }); } catch (e) { /* ignore */ } }, 80); }
    }
    // the shared engine (public/design/search.js) loads deferred; the index lazily
    let tries = 0;
    this._wait = setInterval(() => {
      if (window.AHVSearch && window.AHVSearch.load) {
        clearInterval(this._wait); this._wait = null;
        window.AHVSearch.load().then(index => {
          const kw = {}; (index.faqs || []).forEach(f => { kw[f.id] = f.kw || []; });
          docs.forEach(x => { x.kw = kw[x.id] || []; });
          engine = window.AHVSearch.createEngine({ classes: index.classes, vocabulary: index.vocabulary, intents: (index.intents || []).filter(i => /^q-/.test(i.target)), programmes: [], pages: [], faqs: docs, ui: index.ui });
          apply();
        }).catch(() => {});
      } else if (++tries > 60) { clearInterval(this._wait); this._wait = null; }
    }, 150);
    return true;
  }
  componentWillUnmount() { if (this._wait) clearInterval(this._wait); if (this._retry) clearTimeout(this._retry); if (this._track) clearTimeout(this._track); }
  renderVals() { return { rootRef: (el) => { this.root = el; } }; }
}`;

const EMPTY = 'No question matches that word. Ask us directly: <a href="https://wa.me/919289838797" target="_blank" rel="noopener noreferrer" style="font-weight:700;display:inline-flex;align-items:center;min-height:44px">WhatsApp +91 92898 38797</a> · <a href="https://ayurvedichealingvillage.com/online-consultation/" style="font-weight:700;display:inline-flex;align-items:center;min-height:44px">Free online consultation</a> · <a href="mailto:info@kairali.com" style="font-weight:700;display:inline-flex;align-items:center;min-height:44px">info@kairali.com</a>. Or clear the filter to see every question.';

function patchTemplate(T, label) {
  let n = 0;
  T = T.replace(/<details data-q="[^"]*"( id="q-\d+")?/g, () => { n += 1; return `<details data-q="${n}" id="q-${String(n).padStart(2, "0")}"`; });
  if (n !== 44) throw new Error(`${label}: expected 44 questions, numbered ${n}`);
  const inputs = (T.match(/<input id="faq-filter(?:-m)?"[^>]*>/g) || []);
  if (inputs.length !== 1) throw new Error(`${label}: expected one filter input, found ${inputs.length}`);
  T = T.replace(/(<input id="faq-filter(?:-m)?"[^>]*?)font-size:1[78]px/, "$1font-size:18px");
  const emptyRe = /(<p data-empty="1"[^>]*>)[\s\S]*?(<\/p>)/;
  if (!emptyRe.test(T)) throw new Error(`${label}: empty-state paragraph not found`);
  T = T.replace(emptyRe, `$1${EMPTY}$2`);
  for (const need of ['id="q-01"', 'id="q-44"', "font-size:18px", "wa.me/919289838797", "online-consultation", "info@kairali.com"]) if (!T.includes(need)) throw new Error(`${label}: postcondition ${need}`);
  return T;
}

let touched = 0;
for (const side of ["desktop", "mobile"]) {
  // served view
  const id = `ahv-page-faqs-and-downloads-${side}`;
  const file = path.join(SITE, "public/ahv/views", id + ".json");
  const view = JSON.parse(fs.readFileSync(file, "utf8"));
  const t2 = patchTemplate(view.template, id);
  const changed = t2 !== view.template || !view.logic.startsWith(LOGIC.slice(0, 40));
  view.template = t2; view.logic = LOGIC;
  if (changed) { touched += 1; if (!DRY) fs.writeFileSync(file, JSON.stringify(view) + "\n"); }
  console.log(`${changed ? (DRY ? "[dry] " : "fixed  ") : "as-is  "}${id}`);
  // overlay component
  const oc = path.join(SITE, "english-candidate/package-overlay", `AHV Page FAQs and Downloads ${side === "desktop" ? "Desktop" : "Mobile"}.dc.html`);
  let src = fs.readFileSync(oc, "utf8");
  const open = src.indexOf("<x-dc>"), close = src.lastIndexOf("</x-dc>");
  if (open < 0 || close < 0) throw new Error(oc + ": no <x-dc>");
  const inner = patchTemplate(src.slice(open + 6, close), path.basename(oc));
  const sm = src.match(/(<script type="text\/x-dc" data-dc-script[^>]*>)([\s\S]*?)(<\/script>)/);
  if (!sm) throw new Error(oc + ": no logic script");
  const out = src.slice(0, open + 6) + inner + src.slice(close).replace(sm[0], () => sm[1] + "\n" + LOGIC + "\n" + sm[3]); // function form: a string replacement would expand the src.slice(close).replace(sm[0], sm[1] + "\n" + LOGIC + "\n" + sm[3]); inside the logic
  const oChanged = out !== src;
  if (oChanged) { touched += 1; if (!DRY) fs.writeFileSync(oc, out); }
  console.log(`${oChanged ? (DRY ? "[dry] " : "fixed  ") : "as-is  "}${path.basename(oc)}`);
}
console.log(`repair-faq-search${DRY ? " (dry)" : ""}: ${touched} file(s) changed`);
