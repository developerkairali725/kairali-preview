#!/usr/bin/env node
// Chapter 08 of the long-form advertising route carries 27 programme names, verbatim from the
// live page, stale, as plain text with no links. Owner ruling 2026-09-21: replace them with the
// rebuild's own set.
//
// The source is the CANONICAL dataset the /all-programs/ finder renders —
// public/ahv/assets/all-programs-data.js, generated from the owner's own
// planning/owner-decisions-2026-09-07/FINDER-COPY-AND-DATA.json — not the rendered HTML, and
// nothing here is invented. Every route is asserted against route-manifest.json: a programme
// whose page does not exist is a hard failure, never a plain-text fallback.
//
// Emits the ordered set for the wiring plus a readable note for the drop folder. Writes no
// markup: chapter 08's three-column hairline layout is the designer's, and MODE A leaves it alone.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const site = resolve(here, '..');
const repo = resolve(site, '../..');

const DATA = resolve(site, 'public/ahv/assets/all-programs-data.js');
const MANIFEST = resolve(site, 'english-candidate/route-manifest.json');
const OUT_JSON = resolve(site, 'english-candidate/long-form-programme-set.json');
const OUT_NOTE = resolve(
  repo,
  'launches/ayurvedichealingvillage.com/design-intake/LONG-FORM-ADVERTISING/notes/chapter-08-programme-set.md',
);

const COLUMNS = 3;

function loadFinder() {
  const w = {};
  new Function('window', readFileSync(DATA, 'utf8'))(w);
  if (!w.AHV_FINDER?.programmes?.length) throw new Error(`no programmes in ${DATA}`);
  return w.AHV_FINDER;
}

function manifestRoutes() {
  const m = JSON.parse(readFileSync(MANIFEST, 'utf8'));
  const norm = (r) => String(r).replace(/\.html$/, '').replace(/\/$/, '');
  return new Set(
    m.routes.map((r) => norm(typeof r === 'string' ? r : r.route ?? r.path ?? r.url)),
  );
}

function ist(d = new Date()) {
  const p = new Intl.DateTimeFormat('en-CA', {
    timeZone: 'Asia/Kolkata', hour12: false,
    year: 'numeric', month: '2-digit', day: '2-digit',
    hour: '2-digit', minute: '2-digit', second: '2-digit',
  }).formatToParts(d).reduce((a, x) => ((a[x.type] = x.value), a), {});
  return `${p.year}-${p.month}-${p.day} ${p.hour}:${p.minute}:${p.second} IST`;
}

const finder = loadFinder();
const known = manifestRoutes();
const norm = (r) => String(r).replace(/\.html$/, '').replace(/\/$/, '');

const missing = finder.programmes.filter((p) => !known.has(norm(p.route)));
if (missing.length) {
  console.error(`FAIL — ${missing.length} programme route(s) not in route-manifest.json:`);
  for (const p of missing) console.error(`  ${p.name} -> ${p.route}`);
  process.exit(1);
}

const programmes = finder.programmes.map((p, i) => ({
  order: i + 1,
  name: p.name,
  sanskrit: p.sanskrit ?? null,
  href: p.route,
  categories: p.categories,
  durationDisplay: p.durationDisplay ?? null,
  priceFromINR: p.from?.INR ?? null,
  validTo: p.validTo ?? null,
}));

// Balanced columns, read DOWN each one, so the owner-given order survives the layout.
const per = Math.ceil(programmes.length / COLUMNS);
const columns = Array.from({ length: COLUMNS }, (_, c) =>
  programmes.slice(c * per, (c + 1) * per).map((p) => p.order),
);

const expiring = programmes.filter((p) => p.validTo && p.validTo <= '2026-09-30');

writeFileSync(OUT_JSON, `${JSON.stringify({
  why: 'Chapter 08 of the long-form advertising route. Owner ruling 2026-09-21: use the rebuild\'s set, not the 27 stale live names.',
  source: 'public/ahv/assets/all-programs-data.js (window.AHV_FINDER.programmes) — generated from planning/owner-decisions-2026-09-07/FINDER-COPY-AND-DATA.json',
  generated: ist(),
  count: programmes.length,
  routesVerifiedAgainst: 'english-candidate/route-manifest.json',
  routesMissing: 0,
  columns,
  programmes,
}, null, 2)}\n`);

const money = (n) => (n == null ? '—' : `₹${n.toLocaleString('en-US')}`);
const rows = programmes
  .map((p) => `| ${p.order} | [${p.name}](${p.href}) | ${p.sanskrit ?? '—'} | ${p.categories.join(', ')} | ${p.durationDisplay ?? '—'} | ${money(p.priceFromINR)} |`)
  .join('\n');

writeFileSync(OUT_NOTE, `# Chapter 08 — the programme set, resolved

Generated by \`tools/build-long-form-programme-set.mjs\` at ${ist()}. Do not hand-edit; re-run it.

**Handover item 1**, owner ruling 2026-09-21: *"update the names and offering as per latest"* —
answered with the rebuild's own set rather than a fresh list, because the rebuild already carries
the owner's decided one. Source: \`window.AHV_FINDER.programmes\` in
\`public/ahv/assets/all-programs-data.js\`, itself generated from
\`planning/owner-decisions-2026-09-07/FINDER-COPY-AND-DATA.json\`. Nothing here is invented.

**${programmes.length} programmes, and all ${programmes.length} routes exist** — asserted against
\`english-candidate/route-manifest.json\`, 0 missing. The handover asks that every name resolve to a
real route and that hrefs be added; the hrefs below are those routes.

Order is the dataset's, which is the owner-given one — not alphabetical. Columns are a balanced
split read DOWN each column (${columns.map((c) => c.length).join(' / ')}), so the order survives the
three-column hairline layout. The layout itself is untouched: MODE A, the design is the designer's.

Category spread: ${Object.entries(finder.counts).filter(([k]) => k !== 'unique').map(([k, v]) => `${k} ${v}`).join(' · ')}.

| # | programme | Sanskrit | categories | minimum | from |
|---|---|---|---|---|---|
${rows}

## One thing to decide before this ships

${expiring.length} of the ${programmes.length} price rows carry \`validTo: 2026-09-30\` — the dated
tariff snapshot expires within days of this note. The prices above are correct today and stale on
1 October. If chapter 08 is to print prices at all, the set needs the 2026-27 tariff first; if it
prints names only, this does not arise. Machine data, not a judgment: the dates are in the dataset.
`);

console.log(`programmes      ${programmes.length}`);
console.log(`routes missing  0 of ${programmes.length}`);
console.log(`columns         ${columns.map((c) => c.length).join(' / ')}`);
console.log(`price rows expiring 2026-09-30  ${expiring.length}`);
console.log(`wrote ${OUT_JSON.replace(`${repo}/`, '')}`);
console.log(`wrote ${OUT_NOTE.replace(`${repo}/`, '')}`);
