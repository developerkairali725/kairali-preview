#!/usr/bin/env node
/**
 * AHV — derive the list of view families the sitewide consistency layer
 * must NOT touch, from the served views themselves.
 *
 * WHY. D-20260921-14 locks the approved homepage and the programme
 * ("package") pages; the owner's 22 Sep final-build directive
 * (D-20260922-13) names the homepage and the package pages as the GOLD
 * STANDARD every other family is measured against. The consistency layer
 * (public/design/consistency.css + consistency.js) therefore keys on
 * `data-ahv-consistency="1"`, which app/(english)/_families/design-view.tsx
 * emits only for families NOT in this list. The list is derived, never
 * hand-typed, so a family cannot be locked or unlocked by a typo:
 *
 *   · homepage                — the one home view
 *   · package pages           — every desktop view whose template carries the
 *                               programme page's `id="package"` section
 *   · finder hubs             — templates labelled "… finder" or carrying the
 *                               `data-ahv-finder-block="1"` mark that
 *                               tools/build-finder-views.mjs writes into every hub
 *   · course pages            — the owner-built course family and its hub,
 *                               generated by tools/build-course-views.mjs
 *   · the packages listing    — /ayurvedic-treatment-packages.html, measured
 *                               as gold in the 22 Sep census
 *
 * Output: english-candidate/consistency-locked-families.json (committed).
 * Re-run after any import; the file is read at build time by design-view.tsx.
 *
 *   node tools/build-consistency-lock.mjs [--dry]
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const SITE = join(dirname(fileURLToPath(import.meta.url)), "..");
const DRY = process.argv.includes("--dry");
const VIEWS = join(SITE, "public/ahv/views");
const OUT = join(SITE, "english-candidate/consistency-locked-families.json");

// A view id as design-view.tsx derives the family: the "ahv-page-" prefix and
// the "-desktop"/"-mobile" suffix stripped. The home views are the exception —
// home-hi-fi-v4.json / home-mobile.json carry neither, so every .json is read.
const fam = (file) => file.replace(/\.json$/, "").replace(/^ahv-page-/, "").replace(/-(desktop|mobile)$/, "");
const locked = new Map(); // family -> reason

for (const file of readdirSync(VIEWS).filter((f) => f.endsWith(".json") && !/-mobile\.json$/.test(f)).sort()) {
  const view = JSON.parse(readFileSync(join(VIEWS, file), "utf8"));
  const t = view.template || "";
  const f = fam(file);
  const label = (t.match(/data-screen-label="([^"]*)"/) || [])[1] || "";
  if (/^home(-|$)/.test(f)) locked.set(f, "homepage (D-20260921-14)");
  else if (/\bid="package"/.test(t)) locked.set(f, "package page (D-20260921-14; gold standard D-20260922-13)");
  else if (/finder — /i.test(label) || /data-ahv-finder-block="1"/.test(t)) locked.set(f, "finder hub (tools/build-finder-views.mjs)");
  else if (/^course-/.test(f) || /^ayurveda-training-program/.test(f)) locked.set(f, "course family (tools/build-course-views.mjs)");
  else if (f === "ayurvedic-treatment-packages") locked.set(f, "packages listing, measured as gold (22 Sep census)");
}

const out = {
  generatedBy: "tools/build-consistency-lock.mjs",
  rule: "families listed here never receive data-ahv-consistency; public/design/consistency.* cannot reach them",
  families: Object.fromEntries([...locked.entries()].sort()),
};
const json = JSON.stringify(out, null, 2) + "\n";
if (!DRY) writeFileSync(OUT, json);
console.log(`${DRY ? "[dry] " : ""}${locked.size} locked families → ${OUT.replace(SITE + "/", "")}`);
for (const [k, why] of [...locked.entries()].sort()) console.log(`  ${k.padEnd(40)} ${why}`);
