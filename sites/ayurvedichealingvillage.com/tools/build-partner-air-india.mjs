// /kairali-air-india-maharaja-club.html is a partnership page (owner: "a tie-up, not a campaign" — tools/build-site-tree.mjs),
// so the landing-page translation exclusion does not apply to it (parent locale review 29 Sep 2026: every locale linked it
// to an English page). It renders on the campaign-retreat template, whose dataset holds all seven campaign records; the
// l10n extractor reads whole files, so including the route as-is would translate the six owner-excluded campaign pages too.
// This tool gives the partner route its OWN view pair and dataset, generated from the campaign ones (re-run it after any
// campaign-retreat repair so the copy stays in step):
//   · public/ahv/views/ahv-page-campaign-retreat--air-india-{desktop,mobile}.json = the campaign-retreat views with the
//     dataset script swapped (design-view strips the "--variant" suffix, so data-ahv-family stays "campaign-retreat"
//     and public/design/campaign.css keeps applying);
//   · public/ahv/assets/partner-air-india-data.js = window.AHV_CAMPAIGN with only the partner record;
//   · english-candidate/route-manifest.json: the route points at them.
//   node tools/build-partner-air-india.mjs [--check]
import fs from "node:fs";

const PATH = "/kairali-air-india-maharaja-club.html";
const SRC_DATA = "public/ahv/assets/campaign-family-data.js";
const OUT_DATA = "public/ahv/assets/partner-air-india-data.js";
const SRC_SCRIPT = "/ahv/assets/campaign-family-data.js";
const OUT_SCRIPT = "/ahv/assets/partner-air-india-data.js";
const check = process.argv.includes("--check");
const writes = [];
const put = (f, s) => { if (!fs.existsSync(f) || fs.readFileSync(f, "utf8") !== s) writes.push(f); if (!check) fs.writeFileSync(f, s); };
const indentOf = (raw) => { const m = raw.match(/^\{\n( +)"/); return m ? m[1].length : 0; };

for (const v of ["desktop", "mobile"]) {
  const srcFile = `public/ahv/views/ahv-page-campaign-retreat-${v}.json`;
  const raw = fs.readFileSync(srcFile, "utf8");
  const view = JSON.parse(raw);
  if (!view.scripts.includes(SRC_SCRIPT)) throw new Error(`${srcFile}: dataset script not found`);
  view.id = `ahv-page-campaign-retreat--air-india-${v}`;
  view.scripts = view.scripts.map((s) => (s === SRC_SCRIPT ? OUT_SCRIPT : s));
  view.partnerNote = "generated by tools/build-partner-air-india.mjs from ahv-page-campaign-retreat-" + v + " (do not edit by hand)";
  put(`public/ahv/views/${view.id}.json`, JSON.stringify(view, null, indentOf(raw)) + (raw.endsWith("\n") ? "\n" : ""));
}

const w = {};
new Function("window", fs.readFileSync(SRC_DATA, "utf8"))(w);
const data = w.AHV_CAMPAIGN;
const rec = (data.routes || []).find((r) => r.path === PATH);
if (!rec) throw new Error(`${PATH} record not found in ${SRC_DATA}`);
// The campaign views read the frozen campaign chrome (logo, header contact, footer) from routes[0]; the split keeps only
// those three fields there, under a path no route resolves to, then the partner record.
const r0 = data.routes[0];
const chrome = { path: "#campaign-chrome", slug: "campaign-chrome", kind: "chrome", logo: r0.logo, headerContact: r0.headerContact, footer: r0.footer };
put(OUT_DATA, "// generated by tools/build-partner-air-india.mjs from campaign-family-data.js (campaign chrome + partner record; do not edit by hand)\nwindow.AHV_CAMPAIGN = " + JSON.stringify({ ...data, routes: [chrome, rec] }) + ";\n");

const mf = "english-candidate/route-manifest.json";
const mraw = fs.readFileSync(mf, "utf8");
const m = JSON.parse(mraw);
const r = m.routes.find((x) => x.path === PATH);
if (!r) throw new Error("route not in manifest");
Object.assign(r, { desktopView: "ahv-page-campaign-retreat--air-india-desktop", mobileView: "ahv-page-campaign-retreat--air-india-mobile", dataset: "assets/partner-air-india-data.js" });
put(mf, JSON.stringify(m, null, indentOf(mraw)) + (mraw.endsWith("\n") ? "\n" : ""));

console.log(writes.length ? (check ? "would write: " : "wrote: ") + writes.join(", ") : "up to date");
if (check && writes.length) process.exit(1);
