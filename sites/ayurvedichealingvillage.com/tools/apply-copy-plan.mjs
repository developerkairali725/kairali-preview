// Apply exact-string copy plans to the English SOURCE (views, datasets, overlays, candidate JSON) — all or nothing.
//   node tools/apply-copy-plan.mjs <plan.json> [...more plans] [--check]
// A plan is {"entries":[...]} (or a bare array). Each entry:
//   {id, file: "<site-relative path>" | files: [...], old, new, count | countPerFile:{file:n}}   exact occurrences, or
//   {id, auto: true, old, new, min}                                        every source file under AUTO_ROOTS, total >= min
//   {id, op: "manifestMeta", path: "/route/", set: {title, description, ogTitle, ogDescription}}
// Occurrences count the raw string AND its JSON-escaped form (strings inside JSON views / dataset literals).
// Nothing is written unless EVERY entry matches its expected count; an entry already applied (0 old, >=1 new)
// is reported and skipped, so a re-run is idempotent. Prerender snapshots and l10n output are regenerated by their
// own tools and are never edited here.
import fs from "node:fs";
import path from "node:path";

const SITE = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/%20/g, " ")), "..");
const CHECK = process.argv.includes("--check");
const planFiles = process.argv.slice(2).filter((a) => !a.startsWith("--"));
if (!planFiles.length) { console.error("usage: apply-copy-plan.mjs <plan.json> [...] [--check]"); process.exit(2); }

const AUTO_ROOTS = ["public/ahv/views", "public/ahv/assets", "english-candidate"];
const AUTO_SKIP = /(^|\/)(prerender|prerender-tmp|node_modules|copy-plans)(\/|$)/;
const walk = (dir) => fs.readdirSync(path.join(SITE, dir), { withFileTypes: true }).flatMap((d) => {
  const rel = path.join(dir, d.name);
  if (AUTO_SKIP.test(rel)) return [];
  if (d.isDirectory()) return walk(rel);
  return /\.(json|js|html)$/.test(d.name) ? [rel] : [];
});
let autoFiles;
const autoList = () => (autoFiles ??= AUTO_ROOTS.flatMap(walk));

const forms = (s) => [...new Set([s, JSON.stringify(s).slice(1, -1)])];
const count = (hay, s) => (s ? hay.split(s).length - 1 : 0);
const occurrences = (src, s) => forms(s).reduce((n, f) => n + count(src, f), 0);

const cache = new Map();
const read = (f) => { if (!cache.has(f)) cache.set(f, fs.readFileSync(path.join(SITE, f), "utf8")); return cache.get(f); };
const dirty = new Set();

const entries = planFiles.flatMap((p) => { const j = JSON.parse(fs.readFileSync(p, "utf8")); return (Array.isArray(j) ? j : j.entries).map((e) => ({ ...e, plan: path.basename(p) })); });
const log = []; let bad = 0;

for (const e of entries) {
  if (e.op === "manifestMeta") {
    const f = "english-candidate/route-manifest.json";
    const m = JSON.parse(read(f));
    const r = m.routes.find((x) => x.path === e.path);
    if (!r) { bad++; log.push(`FAIL ${e.id}: route ${e.path} not in manifest`); continue; }
    const same = Object.entries(e.set).every(([k, v]) => r.metadata[k] === v);
    if (same) { log.push(`ok   ${e.id}: already applied (${e.path})`); continue; }
    Object.assign(r.metadata, e.set);
    cache.set(f, JSON.stringify(m, null, 1) + (read(f).endsWith("\n") ? "\n" : "")); dirty.add(f);
    log.push(`edit ${e.id}: ${e.path} metadata ${Object.keys(e.set).join(",")}`);
    continue;
  }
  const files = e.auto ? autoList().filter((f) => read(f).includes(e.old) || forms(e.old).some((x) => read(f).includes(x))) : (e.files ?? [e.file]);
  let total = 0, already = 0; const per = [], todo = [];
  for (const f of files) {
    if (!fs.existsSync(path.join(SITE, f))) { bad++; log.push(`FAIL ${e.id}: missing file ${f}`); continue; }
    const src = read(f); const have = occurrences(src, e.old); const want = e.countPerFile ? e.countPerFile[f] : e.count;
    // already applied: a deletion whose text is gone, or a replacement whose new text is present `want` times
    // (checked BEFORE the count test, so a replacement that contains its own old text is never applied twice)
    const applied = e.new === "" ? have === 0 : occurrences(src, e.new) >= want && (have === 0 || e.new.includes(e.old));
    if (!e.auto && applied) { already++; per.push(`${f}: already`); continue; }
    if (!e.auto && have !== want) {
      bad++; log.push(`FAIL ${e.id}: ${f} want ${want}, have ${have} — "${e.old.slice(0, 70)}…"`); continue;
    }
    total += have; per.push(`${f}: ${have}`); todo.push(f);
  }
  if (e.auto && total < (e.min ?? 1)) {
    // A removal (new "") leaves nothing to find once applied: zero remaining occurrences IS the applied state.
    const done = e.new === "" || autoList().some((f) => occurrences(read(f), e.new) > 0);
    if (total === 0 && done) { log.push(`ok   ${e.id}: already applied`); continue; }
    bad++; log.push(`FAIL ${e.id}: auto found ${total} < min ${e.min ?? 1} — "${e.old.slice(0, 70)}…"`); continue;
  }
  for (const f of todo) {
    let src = read(f); const fo = forms(e.old), fn = forms(e.new);
    if (!fo.some((x) => src.includes(x))) continue;
    fo.forEach((x, i) => { src = src.split(x).join(fn[i] ?? fn[0]); });
    cache.set(f, src); dirty.add(f);
  }
  log.push(`${todo.length ? "edit" : "ok  "} ${e.id}: ${per.join("; ")}${already ? ` (+${already} already)` : ""}`);
}

console.log(log.join("\n"));
if (bad) { console.error(`\n${bad} failure(s) — NOTHING written`); process.exit(1); }
if (CHECK) { console.log(`\n--check: ${dirty.size} file(s) would change`); process.exit(0); }
for (const f of dirty) fs.writeFileSync(path.join(SITE, f), cache.get(f));
console.log(`\nwrote ${dirty.size} file(s)`);
