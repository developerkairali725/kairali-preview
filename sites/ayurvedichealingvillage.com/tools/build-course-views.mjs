/**
 * AHV Ayurveda training courses — one page per course on the training template.
 *
 * WHY. The five courses were generic article pages (legacy sidebar rendered
 * as body text, no structure). Owner ruling D-20260916-10 / 2026-09-17: give
 * them proper pages. Each course becomes a data-driven instance of the
 * training hub view (ahv-page-ayurveda-training-programs-*): same template
 * and logic, its own dataset (public/ahv/assets/course-<code>-data.js, the
 * shape the logic already reads), its own head, eyebrow, h1, intro and image.
 * Content: english-candidate/course-pages.json. Course rows (code, days,
 * hours, level, audience) come from the hub's own dataset and are re-ordered
 * with the page's course first. Idempotent; anchors match exactly once.
 *
 * Usage: node tools/build-course-views.mjs [--dry]
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SITE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const VIEWS = path.join(SITE, "public/ahv/views");
const ASSETS = path.join(SITE, "public/ahv/assets");
const SPEC = JSON.parse(fs.readFileSync(path.join(SITE, "english-candidate/course-pages.json"), "utf8"));
const MANIFEST = JSON.parse(fs.readFileSync(path.join(SITE, "english-candidate/route-manifest.json"), "utf8")).routes;
const DRY = process.argv.includes("--dry");
const HOST = "https://ayurvedichealingvillage.com";
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const rx = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
function once(text, find, repl, label) {
  const re = find instanceof RegExp ? find : new RegExp(rx(find));
  const n = (text.match(new RegExp(re.source, "g" + re.flags.replace("g", ""))) || []).length;
  if (n !== 1) throw new Error(`${label}: expected exactly one match, found ${n}`);
  return text.replace(re, repl);
}

// The hub dataset is the source for course rows and footer links.
const hubSrc = fs.readFileSync(path.join(ASSETS, "ayurveda-training-data.js"), "utf8");
const hub = new Function(hubSrc.replace("window.AHV_AYURVEDA_TRAINING =", "return"))();
if (!hub || !Array.isArray(hub.courses) || hub.courses.length !== 5) throw new Error("hub dataset: expected 5 course rows");

for (const c of SPEC.courses) {
  const route = MANIFEST.find((r) => r.path === c.route);
  if (!route) throw new Error("course route not in manifest: " + c.route);
  const md = route.metadata;
  const mine = hub.courses.find((h) => h.href === c.route);
  if (!mine) throw new Error(`hub dataset has no row linking ${c.route}`);
  const others = SPEC.courses.filter((o) => o.route !== c.route);
  const data = {
    route: c.route,
    courses: [mine, ...hub.courses.filter((h) => h !== mine)],
    process: [c.processLead, ...c.steps],
    features: c.features,
    learning: c.learning,
    faq: c.faq,
    relatedLinks: [
      { href: "/ayurveda-training-programme/", label: "Ayurveda Training Programmes — all courses" },
      ...others.map((o) => ({ href: o.route, label: o.name })),
    ],
    footerLinks: hub.footerLinks || [],
  };
  const dataFile = `course-${c.code.toLowerCase()}-data.js`;
  const js = `// ${c.route} — course page data, generated by tools/build-course-views.mjs from english-candidate/course-pages.json (content) and ayurveda-training-data.js (course rows). Do not edit by hand.\nwindow.AHV_AYURVEDA_TRAINING = ${JSON.stringify(data, null, 2)};\n`;
  if (!DRY) fs.writeFileSync(path.join(ASSETS, dataFile), js);

  for (const v of ["desktop", "mobile"]) {
    const base = JSON.parse(fs.readFileSync(path.join(VIEWS, `ahv-page-ayurveda-training-programs-${v}.json`), "utf8"));
    const view = JSON.parse(JSON.stringify(base));
    let T = view.template;
    // Course-specific text first, then the template-wide rename, then the head
    // and h1 - so a course whose own name contains "Ayurveda Training Program"
    // (the Five-Day Intensive, Level One) is never renamed twice.
    T = once(T, />Introducing our Ayurveda Training Program[^<]*<\/p>/, `>${esc(c.intro)}</p>`, `${c.code} ${v} intro`);
    T = once(T, /<img src="\/ahv\/assets\/img\/AHV-Ayurveda-Training-About\.png" alt="[^"]*"/, `<img src="${c.image}" alt="${esc(c.alt)}"`, `${c.code} ${v} image`);
    T = once(T, "Courses &amp; workshops at Kairali", esc(c.eyebrow), `${c.code} ${v} eyebrow`);
    // Breadcrumb current label and the section headings name the course.
    T = T.split("Ayurveda Training Program").join(esc(c.short));
    T = once(T, new RegExp(`(<h1[^>]*>)${rx(esc(c.short))}(<\\/h1>)`), (m, a, z) => `${a}${esc(c.name)}${z}`, `${c.code} ${v} h1`);
    // The breadcrumb's current label is the course name, not the short form used in headings.
    T = once(T, new RegExp(`(<span aria-current="page"[^>]*>)${rx(esc(c.short))}(<\\/span>)`), (m, a, z) => `${a}${esc(c.name)}${z}`, `${c.code} ${v} breadcrumb`);
    T = once(T, /<title>[^<]*<\/title>/, `<title>${esc(md.title)}</title>`, `${c.code} ${v} title`);
    T = once(T, /<meta name="description" content="[^"]*">/, `<meta name="description" content="${esc(md.description)}">`, `${c.code} ${v} description`);
    T = once(T, /<link rel="canonical" href="[^"]*">/, `<link rel="canonical" href="${esc(md.canonical)}">`, `${c.code} ${v} canonical`);
    T = once(T, /<meta property="og:title" content="[^"]*">/, `<meta property="og:title" content="${esc(md.ogTitle || md.title)}">`, `${c.code} ${v} og:title`);
    T = once(T, /<meta property="og:description" content="[^"]*">/, `<meta property="og:description" content="${esc(md.ogDescription || md.description)}">`, `${c.code} ${v} og:description`);
    T = once(T, /<meta property="og:url" content="[^"]*">/, `<meta property="og:url" content="${esc(md.canonical)}">`, `${c.code} ${v} og:url`);
    view.template = T;
    view.scripts = (view.scripts || []).map((s) => (s.endsWith("/ayurveda-training-data.js") ? `/ahv/assets/${dataFile}` : s));
    if (!view.scripts.includes(`/ahv/assets/${dataFile}`)) throw new Error(`${c.code} ${v}: hub script tag not found`);
    view.id = `${c.id}-${v}`;
    view.derivedFrom = base.id;
    view.derivedRoute = c.route;
    if (!DRY) fs.writeFileSync(path.join(VIEWS, view.id + ".json"), JSON.stringify(view, null, 1) + "\n");
  }
  console.log(`${DRY ? "[dry] " : ""}${c.code}: ${c.id}-{desktop,mobile} + ${dataFile} (${c.steps.length} steps, ${c.faq.length} FAQs)`);
}
console.log(`course pages: ${SPEC.courses.length} derived from ahv-page-ayurveda-training-programs-*`);
