CREATE TABLE IF NOT EXISTS `landing-page` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `site` varchar(190) NOT NULL DEFAULT 'ayurvedichealingvillage.com',
  `form_type` varchar(64) NOT NULL DEFAULT 'landing-page',
  `landing_page_path` varchar(255) NOT NULL,
  `form_variant` varchar(64) DEFAULT NULL,
  `fname` varchar(120) NOT NULL,
  `lname` varchar(120) DEFAULT NULL,
  `rdogender` varchar(32) DEFAULT NULL,
  `phone` varchar(40) NOT NULL,
  `email` varchar(254) NOT NULL,
  `country` varchar(120) DEFAULT NULL,
  `duration` varchar(80) DEFAULT NULL,
  `message` text,
  `consent` tinyint(1) NOT NULL DEFAULT 0,
  `consent_at` timestamp NULL DEFAULT NULL,
  `track_id` varchar(190) DEFAULT NULL,
  `campaign_name` varchar(190) DEFAULT NULL,
  `source` varchar(190) DEFAULT NULL,
  `campaign` varchar(190) DEFAULT NULL,
  `medium` varchar(190) DEFAULT NULL,
  `gclid` varchar(255) DEFAULT NULL,
  `fbclid` varchar(255) DEFAULT NULL,
  `utm_source` varchar(190) DEFAULT NULL,
  `utm_medium` varchar(190) DEFAULT NULL,
  `utm_campaign` varchar(190) DEFAULT NULL,
  `utm_term` varchar(190) DEFAULT NULL,
  `utm_keyword` varchar(190) DEFAULT NULL,
  `utm_content` varchar(190) DEFAULT NULL,
  `lead_source_url` varchar(1000) NOT NULL,
  `referrer` varchar(1000) DEFAULT NULL,
  `submit_time` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `submit_ip` varchar(45) DEFAULT NULL,
  `submission_token` char(36) NOT NULL,
  `status` varchar(32) NOT NULL DEFAULT 'new',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_landing_page_submission_token` (`submission_token`),
  KEY `idx_landing_page_path_time` (`landing_page_path`, `submit_time`),
  KEY `idx_landing_page_email` (`email`),
  KEY `idx_landing_page_phone` (`phone`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
